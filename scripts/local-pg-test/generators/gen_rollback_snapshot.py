#!/usr/bin/env python3
"""Generate supabase/rollback/pre_0201_0203_functions.sql.

The pre-apply definitions of the functions 0201, 0202 and 0203 replace,
taken from repository copies whose body md5 equals what production reported
(read-only, 2026-10-30). A copy is only emitted if its md5 matches; anything
that cannot be matched is listed as "capture at apply time" instead of being
guessed. Run from the repository root:

    python3 scripts/local-pg-test/generators/gen_rollback_snapshot.py
"""
